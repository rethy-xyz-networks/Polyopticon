async function get(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

(async () => {
  const paths = {};
  for (const [app, fluent] of Object.entries(ICONS)) {
    const svg = await get(SVG(fluent));
    const inner = svg.match(/<svg[^>]*>([\s\S]*)<\/svg>/)?.[1];
    if (!inner || !/viewBox="0 0 20 20"/.test(svg)) throw new Error(`${fluent}: unexpected SVG`);
    paths[app] = inner.trim();
  }

  const body = Object.entries(paths).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
  fs.writeFileSync(OUT_JS, `// Generated by scripts/build-icons.js — edit the list there, not this file.
// Fluent UI System Icons ${VERSION}, MIT © Microsoft Corporation (assets/fluent-icons-LICENSE.txt).

const PATHS = {
${body}
};

/** An icon as an <svg>, sized by the surrounding font-size and coloured by currentColor. */
export function icon(name) {
  if (!(name in PATHS)) throw new Error(\`Unknown icon: \${name}\`);
  const t = document.createElement('template');
  t.innerHTML = \`<svg class="icon" viewBox="0 0 20 20" aria-hidden="true" data-icon="\${name}">\${PATHS[name]}</svg>\`;
  return t.content.firstChild;
}

/** Replaces el's content with an icon. */
export function setIcon(el, name) {
  el.replaceChildren(icon(name));
  return el;
}

/** Fills every empty element with a data-icon attribute (the static buttons in index.html). */
export function applyIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]:empty')) setIcon(el, el.dataset.icon);
}
`);
  fs.writeFileSync(OUT_LIC, await get(LICENSE));
  console.log(`Wrote ${Object.keys(paths).length} icons to ${path.relative(ROOT, OUT_JS)}`);
})().catch(err => { console.error(err); process.exit(1); });

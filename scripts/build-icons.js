// Builds the renderer's icon set from Fluent UI System Icons. Run once (and after
// adding an icon to the list below):
//
//   node scripts/build-icons.js
//
// Data: @fluentui/svg-icons on jsDelivr (MIT, © Microsoft Corporation,
// github.com/microsoft/fluentui-system-icons). Only the icons listed here are kept.
// Outputs:
//   src/renderer/icons.js                      the SVG paths + icon() / setIcon()
//   src/renderer/assets/fluent-icons-LICENSE.txt

const fs   = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT_JS  = path.join(ROOT, 'src/renderer/icons.js');
const OUT_LIC = path.join(ROOT, 'src/renderer/assets/fluent-icons-LICENSE.txt');

const VERSION = '1.1.300';
const SVG = name => `https://cdn.jsdelivr.net/npm/@fluentui/svg-icons@${VERSION}/icons/${name}_20_regular.svg`;
const LICENSE = 'https://raw.githubusercontent.com/microsoft/fluentui-system-icons/main/LICENSE';

// App name -> Fluent icon name
